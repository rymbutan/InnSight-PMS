#!/usr/bin/env bash
# Generate a .env with strong, randomly generated secrets.
#
# WHY THIS EXISTS
# ---------------
# docker-compose.yml uses `${VAR:?message}` for every secret, so compose REFUSES
# TO START until each one is set. There are deliberately no fallback values any
# more: the previous defaults (`innsight_dev_2025`,
# `innsight_slsu_capstone_jwt_secret_2025`) are published in this repository, and
# a stack that never wrote a .env silently ran on credentials anyone can read.
# The JWT default was even 41 characters long, so it passed the `>= 32` strength
# check in every service and the production hard-fail could never fire.
#
# Requiring the variables only helps if setting them is easy. That is this script.
#
#   bash scripts/gen-env.sh          # write .env (refuses to clobber an existing one)
#   bash scripts/gen-env.sh --force  # regenerate, keeping a timestamped backup
#
# NOTE: regenerating JWT_SECRET invalidates every issued token (everyone is logged
# out), and regenerating POSTGRES_PASSWORD does NOT change the password inside an
# existing pgdata volume — Postgres only reads POSTGRES_PASSWORD when it
# initialises an empty data directory. If you rotate it, also run
# `docker compose down -v` (destroys data) or ALTER the role by hand.

set -euo pipefail
cd "$(dirname "$0")/.."

FORCE=0
[ "${1:-}" = "--force" ] && FORCE=1

if [ -f .env ] && [ "$FORCE" -eq 0 ]; then
  echo "  .env already exists — leaving it alone."
  echo "  Re-run with --force to regenerate (a backup is kept)."
  echo
  echo "  Variables docker-compose.yml requires:"
  for v in POSTGRES_PASSWORD JWT_SECRET SERVICE_JWT_SECRET MINIO_ROOT_PASSWORD ADMIN_INITIAL_PASSWORD; do
    if grep -qE "^${v}=.+" .env; then
      echo "    ✓ $v"
    else
      echo "    ✗ $v   MISSING — add it or compose will refuse to start"
    fi
  done
  exit 0
fi

if [ -f .env ]; then
  # No timestamp from `date` in the filename would be ambiguous across runs.
  backup=".env.backup.$(date +%Y%m%d%H%M%S)"
  cp .env "$backup"
  echo "  Backed up existing .env → $backup"
fi

need() { command -v "$1" >/dev/null 2>&1 || { echo "ERROR: $1 not found; cannot generate secrets safely." >&2; exit 1; }; }
need openssl

# hex for the JWT secret (64 chars, so it clears the >=32 check with room to
# spare and contains nothing that needs quoting in a .env or a URL).
JWT="$(openssl rand -hex 32)"
# base64 minus characters that are awkward inside a postgresql:// URL. The
# DATABASE_URLs in docker-compose.yml interpolate POSTGRES_PASSWORD directly into
# a connection string, so `/`, `+`, `@`, `:` and `?` must not appear or the URL
# silently parses wrong.
safe_pw() { openssl rand -base64 48 | tr -d '\n/+=@:?#' | cut -c1-32; }

# ADMIN_INITIAL_PASSWORD is the one secret a human has to read off a screen and
# type by hand, and five wrong attempts lock the account PERMANENTLY (there is no
# timer, and the only unlock endpoint needs an admin already signed in — so on a
# fresh install, where `admin` is the sole account, a handful of typos costs you
# a trip into psql). Drop the glyphs that render near-identically in most fonts —
# capital I, lowercase l, digit 1, capital O, digit 0 — so a correct read cannot
# turn into a failed login. Still ~140 bits over the remaining 57-character
# alphabet, and comfortably past the seed's >= 12 length check.
typeable_pw() { openssl rand -base64 64 | tr -d '\n/+=@:?#Il1O0' | cut -c1-24; }

cat > .env <<EOF
# InnSight PMS — generated by scripts/gen-env.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ)
#
# DO NOT COMMIT THIS FILE. It is covered by .gitignore.
# Regenerate with: bash scripts/gen-env.sh --force

# Shared signing secret for all service JWTs. Must be >= 32 characters, and must
# not be one of the values published in this repo (each service now rejects those
# by value, not just by length).
JWT_SECRET=$JWT

# SEPARATE key for machine-to-machine tokens (svc: true). Must differ from
# JWT_SECRET: folio/audit/reports used to mint their own admin tokens with the human
# session key, so a compromise of any one of them could forge a login for any user.
SERVICE_JWT_SECRET=$(openssl rand -hex 32)

# Postgres superuser password. Interpolated into every service's DATABASE_URL, so
# it is generated URL-safe. Only read when an EMPTY pgdata volume is initialised.
POSTGRES_PASSWORD=$(safe_pw)

# MinIO object-store root credentials. Nothing in the codebase actually talks to
# MinIO (finding M7) — this exists so compose can start the unused service.
MINIO_ROOT_USER=innsight
MINIO_ROOT_PASSWORD=$(safe_pw)

# Used ONCE, by scripts/db-seed.sh, to create the admin account. The account is
# flagged mustChangePwd, so this value is only valid for a single sign-in and the
# seed never logs it. Must be >= 12 characters. Generated from the reduced,
# unambiguous alphabet because this is the only secret here that gets typed by
# hand — see typeable_pw() above.
ADMIN_INITIAL_PASSWORD=$(typeable_pw)

# Hotel-local timezone — drives business-date/day-boundary logic (night audit,
# daily totals). The Philippines has no DST, so this is a fixed +08:00 offset.
TZ=Asia/Manila

# The address a GUEST can reach — what portal links and QR codes encode.
#
# localhost is correct for a laptop demo, including with the wifi off. It is NOT
# scannable: a phone resolving "localhost" reaches itself, so the app shows an
# on-screen confirmation instead of a scan prompt (see services/_shared/publicUrl.js).
#
# To make QR codes scannable in a lab, set this to the machine's LAN address and put
# both devices on the same network:
#     PUBLIC_BASE_URL=http://192.168.1.20:8080
# Once deployed, set it to the public origin:
#     PUBLIC_BASE_URL=https://innsight.example
# Nothing needs rebuilding — the services read it at start.
PUBLIC_BASE_URL=http://localhost:8080

# ── Outbound mail ───────────────────────────────────────────────────────────
# Left blank, the stack sends to Mailhog: every email is captured at :8025 and
# NOTHING is delivered. That is what you want for development, and it is what a
# fresh .env gives you.
#
# To send real mail, fill these in. For Gmail:
#
#     SMTP_HOST=smtp.gmail.com
#     SMTP_PORT=587
#     SMTP_USER=innsight.local.pms@gmail.com
#     SMTP_PASS=<16-character app password, no spaces>
#     NOTIFY_FROM=InnSight PMS <innsight.local.pms@gmail.com>
#
# SMTP_PASS is an APP PASSWORD, not the account password: Google stopped
# accepting the account password over SMTP in May 2022. Generate one at
# Google Account → Security → 2-Step Verification → App passwords. 2-Step
# Verification has to be ON before that option appears.
#
# NOTIFY_FROM must name the same mailbox as SMTP_USER. Gmail rewrites a From
# header it does not own, so a mismatch does not fail loudly — it just sends
# as somebody else.
#
# Leave SMTP_USER and SMTP_PASS empty and nothing changes: the notifier only
# reaches for STARTTLS and AUTH when both are set, and it REFUSES to send a
# password to a server that will not encrypt the session.
SMTP_HOST=mailhog
SMTP_PORT=1025
SMTP_USER=
SMTP_PASS=
SMTP_SECURE=
# A display name here is worth setting: it is the only part of "no reply" a
# recipient sees before they open the message. A mailbox cannot actually refuse
# replies — see services/_shared/notifier.js — so this, plus the footer the
# notifier appends, is the whole of it.
#     NOTIFY_FROM=InnSight PMS (do not reply) <innsight.local.pms@gmail.com>
NOTIFY_FROM=no-reply@innsight.local
# Optional. Set it to a mailbox somebody actually reads and every message
# carries Reply-To, so a reply lands there instead of in the sending account.
# Left empty, messages are marked auto-generated and say not to reply.
NOTIFY_REPLY_TO=
EOF

chmod 600 .env

echo "  ✓ Wrote .env (mode 600)"
echo
echo "  Your first-login admin password:"
echo
echo "      $(grep '^ADMIN_INITIAL_PASSWORD=' .env | cut -d= -f2-)"
echo
echo "  Copy it now. It is in .env if you lose it, and you will be forced to"
echo "  change it on first sign-in."
echo
echo "  Next:"
echo "      docker compose up -d --build"
echo "      bash scripts/db-seed.sh"
